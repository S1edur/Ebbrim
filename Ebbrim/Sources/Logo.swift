// The Ebbrim logo from the design file (Figma 2215:36705), drawn as shapes
// in its own 239.22 x 53 space and scaled to fit.

private let logoSize = CGSize(width: 239.22, height: 53)

private func logoPath(in r: CGRect, _ draw: (inout Path, (CGFloat, CGFloat) -> CGPoint) -> Void) -> Path {
    let s = min(r.width / logoSize.width, r.height / logoSize.height)
    func pt(_ x: CGFloat, _ y: CGFloat) -> CGPoint { CGPoint(x: r.minX + x * s, y: r.minY + y * s) }
    var p = Path()
    draw(&p, pt)
    return p
}

